CREATE OR REPLACE PACKAGE BODY CUSTOM.READ_AND_POPULATE_DATA AS
	LV_DB_ERR_CODE VARCHAR2(100 CHAR);
	LV_DB_ERR_MSG VARCHAR2(1000 CHAR);
    LV_FILENAME        			VARCHAR2(250 CHAR);
    LV_NOOFCOLUMNS     			NUMBER;
    LV_TABLENAME    			VARCHAR2(100 CHAR);
    LV_INSERTCOLUMNS    		VARCHAR2(4000 CHAR);
	LV_COLUMNSIZE				VARCHAR2(4000 CHAR);
    LV_PRIMKEYCOLUMNS    		VARCHAR2(4000 CHAR);    
    LV_DATECOLUMNWITHFORMAT 	VARCHAR2(4000 CHAR);
    LV_NUMBERCOLUMN    			VARCHAR2(4000 CHAR);
    LV_UPLOAD_BATCH_ID    		VARCHAR2(100 CHAR);
    LV_DELIMITER    			VARCHAR2(10 CHAR);
	LV_DELIMITER_LENGTH			NUMBER;
    LV_ADDITIONALPARAM      	VARCHAR2(1000 CHAR);
	LV_BANKID    				VARCHAR2(8 CHAR);
    LV_UPLOADSTRING    			CLOB;
    LV_RECSRLNUM              	VARCHAR2(8 CHAR);
	LV_TMPRECSRLNUM				NUMBER;
	
	TYPE LV_COLLECTION IS TABLE OF VARCHAR2(1000) INDEX BY BINARY_INTEGER;
	LV_RECORDCOLDATA 			LV_COLLECTION;
	LV_INSCOLDATAWITHNUM 		LV_COLLECTION;
	LV_COLSIZEDATA    			LV_COLLECTION;
	LV_DATECOLDATAWITHFORMAT 	LV_COLLECTION;
	LV_NUMCOLDATA 				LV_COLLECTION;
	LV_PRIMKEYCOLDATA 			LV_COLLECTION;
	LV_ADDNLPARAMDATA	 		LV_COLLECTION;	
	LV_TRIMCOLDATA		 		LV_COLLECTION;
	LV_IGNORECOLSIZECOLDATA		LV_COLLECTION;
	LV_RECDATACOUNT				NUMBER:=0;
	LV_DATECOLDATACOUNT			NUMBER:=0;
	LV_NUMCOLDATACOUNT			NUMBER:=0;
	LV_COLSIZEDATACOUNT			NUMBER:=0;
	LV_INSCOLDATAWITHNUMCOUNT	NUMBER:=0;
	LV_ADDNLPARAMCOUNT			NUMBER:=0;
	LV_PRIMKEYCOLCOUNT			NUMBER:=0;	
	LV_TRIMCOLCOUNT				NUMBER:=0;
	LV_IGNORECOLSIZECOLCOUNT	NUMBER:=0;
	
	LV_INDEX					NUMBER :=1;
	LV_INDEX1					NUMBER :=1;
	LV_DELIMPOS                	NUMBER :=0;
	LV_DELIMPOS1				NUMBER :=0;
	LV_DELIMPOS2				NUMBER :=0;
	LV_ADDNLPARAMID				VARCHAR2(4000 CHAR);
	LV_ADDNLPARAMVALUE			VARCHAR2(4000 CHAR);
	LV_TEMPSTR                 	CLOB;
	LV_UPDATECOLUMNS        	CLOB;
	LV_ERR_MSG					CLOB;
	LV_UPDATE_QUERY				CLOB;
	LV_SPLITDATECOLUMNS     	NUMBER;
	LV_SPLITDATECOLFORMAT   	VARCHAR2(100 CHAR);
	LV_SPLITCOLUMNS 			VARCHAR2(100 CHAR);
	LV_SPLITCOLUMNNUM			VARCHAR2(100 CHAR);
	LV_CURSOR_QUERY				VARCHAR2(500 CHAR);
	LV_CHECKDATE				NUMBER;
	LV_DATE						VARCHAR2(100 CHAR);
	LV_CHECKNUMBER          	VARCHAR2(10  CHAR);
	LV_RECNUMFORDATESANDNUMBERS VARCHAR2(4000 CHAR);
	LV_STRING					VARCHAR2(100 CHAR);
	LV_START_END_TIME			VARCHAR2(100 CHAR);
	
PROCEDURE READ_AND_POPULATE_DATA_PROC(UPL_FILE_NAME IN VARCHAR2,NO_OF_COLS IN NUMBER,TABLE_NAME IN VARCHAR2,INSERT_COLS IN VARCHAR2,COLS_SIZE IN VARCHAR2,PRIMARY_COLS IN VARCHAR2,DATE_COLS_WITH_FORMAT IN VARCHAR2,NUMBER_COLS IN VARCHAR2,UPLOAD_BATCH_ID IN VARCHAR2,DELIMITER IN VARCHAR2,ADDITIONAL_PARAM IN VARCHAR2,BANK_ID IN VARCHAR2) IS
TYPE DYNCURSORTYPE  IS REF CURSOR;
CURSOR01    		DYNCURSORTYPE;
BEGIN
	LV_FILENAME       	  	:= UPL_FILE_NAME;
    LV_NOOFCOLUMNS        	:= NO_OF_COLS;
    LV_TABLENAME          	:= TABLE_NAME;
    LV_INSERTCOLUMNS      	:= INSERT_COLS;
	LV_COLUMNSIZE           := COLS_SIZE;
	LV_PRIMKEYCOLUMNS      	:= PRIMARY_COLS;
    LV_DATECOLUMNWITHFORMAT := DATE_COLS_WITH_FORMAT;
    LV_NUMBERCOLUMN         := NUMBER_COLS;
    LV_UPLOAD_BATCH_ID      := UPLOAD_BATCH_ID;
	LV_DELIMITER			:= DELIMITER;
	LV_ADDITIONALPARAM      := ADDITIONAL_PARAM;
    LV_BANKID      			:= BANK_ID;
	
	LV_DELIMITER_LENGTH		:= LENGTH(LV_DELIMITER);
	
	LV_CURSOR_QUERY := 'SELECT UPLOAD_STRING,UPLOAD_REC_SRL_NUM FROM ' || LV_TABLENAME || ' WHERE UPLOAD_FILE_NAME=' || '''' || LV_FILENAME || '''' || ' AND UPLOAD_BATCH_ID=' || '''' || LV_UPLOAD_BATCH_ID || '''' || ' AND BANK_ID=' || '''' || LV_BANKID || '''';
	
	OPEN CURSOR01 FOR LV_CURSOR_QUERY;
	LV_START_END_TIME := TO_CHAR(SYSDATE,'DD-MM-YYYY HH24:MI:SS');
	DBMS_OUTPUT.PUT_LINE('---------------------------------------------------------------------------------------------------------------------------------');
	DBMS_OUTPUT.PUT_LINE('EXECUTION START:'||LV_START_END_TIME);
	IF( CURSOR01%ISOPEN)  THEN
	--{
		LOOP
			FETCH CURSOR01 INTO
			LV_UPLOADSTRING,LV_RECSRLNUM;
			
			IF((LV_RECSRLNUM IS NULL) OR (TRIM(LV_RECSRLNUM) = ''))THEN
				LV_RECSRLNUM := '0';
			END IF;
			
			LV_RECDATACOUNT				:=0;
			LV_DATECOLDATACOUNT			:=0;
			LV_NUMCOLDATACOUNT			:=0;
			LV_COLSIZEDATACOUNT			:=0;
			LV_INSCOLDATAWITHNUMCOUNT	:=0;
			LV_ADDNLPARAMCOUNT			:=0;
			LV_PRIMKEYCOLCOUNT			:=0;
			LV_TRIMCOLCOUNT				:=0;
			LV_IGNORECOLSIZECOLCOUNT	:=0;
			LV_UPDATECOLUMNS            :='';
			LV_ERR_MSG					:=NULL;
			LV_RECNUMFORDATESANDNUMBERS :='';
			
			IF(CURSOR01%NOTFOUND) THEN
			--{
				LV_START_END_TIME := TO_CHAR(SYSDATE,'DD-MM-YYYY HH24:MI:SS');
				DBMS_OUTPUT.PUT_LINE('EXECUTION END:'||LV_START_END_TIME);
				CLOSE CURSOR01;
				DBMS_OUTPUT.PUT_LINE('RETURN FROM LINE NUM 134'); 
				RETURN;
			--}
			END IF;
			
			DBMS_OUTPUT.PUT_LINE('---------------------------------------------------------------------------------------------------------------------------------');
			DBMS_OUTPUT.PUT_LINE('RECORD SERIAL NUMBER: '||LV_RECSRLNUM);
			DBMS_OUTPUT.PUT_LINE(LV_UPLOADSTRING);
						
			BEGIN
			--{
				IF LV_NOOFCOLUMNS IS NULL OR LV_FILENAME IS NULL OR LV_INSERTCOLUMNS IS NULL OR LV_TABLENAME IS NULL OR LV_UPLOAD_BATCH_ID IS NULL OR LV_DELIMITER IS NULL THEN
				--{
					DBMS_OUTPUT.PUT_LINE('RETURN FROM LINE NUM 147'); 
					RETURN;
				--}
				END IF ;
			--}
			END;
			
			BEGIN
			--{
				LV_TEMPSTR := LV_UPLOADSTRING;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_ERR_MSG := LV_ERR_MSG || '|' || 'UPLOADSTRING IS BLANK';
				END IF;
			--}
			END;
			
			BEGIN
			--{
				LV_TEMPSTR := LV_UPLOADSTRING;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_RECDATACOUNT := 0;
				ELSE
					LOOP
						LV_DELIMPOS  := INSTR (LV_TEMPSTR, LV_DELIMITER);
						DBMS_OUTPUT.PUT_LINE('LV_DELIMPOS: '||LV_DELIMPOS);
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
							LV_RECORDCOLDATA(LV_INDEX) := LV_TEMPSTR ;
							EXIT;
						ELSE
							LV_RECORDCOLDATA(LV_INDEX) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
							LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + LV_DELIMITER_LENGTH);
							DBMS_OUTPUT.PUT_LINE('LV_RECORDCOLDATA(LV_INDEX): '||LV_RECORDCOLDATA(LV_INDEX));
						END IF;
						LV_INDEX := LV_INDEX + 1;
					END LOOP;
					LV_RECDATACOUNT := LV_INDEX;
				END IF;
			--}
			END;
			
			BEGIN
			--{
				DBMS_OUTPUT.PUT_LINE('LV_ADDITIONALPARAM = '||LV_ADDITIONALPARAM); 
				LV_TEMPSTR := LV_ADDITIONALPARAM;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_ADDNLPARAMCOUNT := 0;
				ELSE
					LOOP
						LV_DELIMPOS  := INSTR (LV_TEMPSTR, '~');				
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
							LV_ADDNLPARAMDATA(LV_INDEX) := LV_TEMPSTR ;
							EXIT;
						ELSE
							LV_ADDNLPARAMDATA(LV_INDEX) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
							LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
						END IF;
						LV_INDEX := LV_INDEX + 1;
					END LOOP;
					LV_ADDNLPARAMCOUNT := LV_INDEX;
				END IF;
			--}
			END;
			
			BEGIN
			--{
				LV_TEMPSTR := LV_INSERTCOLUMNS;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_INSCOLDATAWITHNUMCOUNT := 0;
				ELSE
					LOOP
						LV_DELIMPOS  := INSTR (LV_TEMPSTR, ',');				
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
							LV_INSCOLDATAWITHNUM(LV_INDEX) := LV_TEMPSTR ;
							EXIT;
						ELSE
							LV_INSCOLDATAWITHNUM(LV_INDEX) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
							LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
						END IF;
						LV_INDEX := LV_INDEX + 1;
					END LOOP;
					LV_INSCOLDATAWITHNUMCOUNT := LV_INDEX;
				END IF;
			--}
			END;
			
			BEGIN
			--{
				LV_TEMPSTR := LV_COLUMNSIZE;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_COLSIZEDATACOUNT := 0;
				ELSE
					LOOP
						LV_DELIMPOS  := INSTR (LV_TEMPSTR, ',');				
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
							LV_COLSIZEDATA(LV_INDEX) := LV_TEMPSTR ;
							EXIT;
						ELSE
							LV_COLSIZEDATA(LV_INDEX) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
							LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
						END IF;
						LV_INDEX := LV_INDEX + 1;
					END LOOP;
					LV_COLSIZEDATACOUNT := LV_INDEX;
				END IF;
			--}
			END;
			
			BEGIN
			--{
				LV_TEMPSTR := LV_DATECOLUMNWITHFORMAT;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_DATECOLDATACOUNT := 0;
				ELSE
					LOOP
						LV_DELIMPOS  := INSTR (LV_TEMPSTR, ',');				
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
							LV_DATECOLDATAWITHFORMAT(LV_INDEX) := LV_TEMPSTR ;
							EXIT;
						ELSE
							LV_DATECOLDATAWITHFORMAT(LV_INDEX) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
							LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
						END IF;
						LV_INDEX := LV_INDEX + 1;
					END LOOP;
					LV_DATECOLDATACOUNT := LV_INDEX;
				END IF;
			--}
			END;
			
			BEGIN
			--{
				LV_TEMPSTR := LV_NUMBERCOLUMN;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_NUMCOLDATACOUNT := 0;
				ELSE
					LOOP
						LV_DELIMPOS  := INSTR (LV_TEMPSTR, ',');				
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
							LV_NUMCOLDATA(LV_INDEX) := LV_TEMPSTR;
							EXIT;
						ELSE
							LV_NUMCOLDATA(LV_INDEX) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
							LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
						END IF;
						LV_INDEX := LV_INDEX + 1;
					END LOOP;
					LV_NUMCOLDATACOUNT := LV_INDEX;
				END IF;
			--}
			END;
			
			BEGIN
			--{
				LV_TEMPSTR := LV_PRIMKEYCOLUMNS;
				LV_INDEX := 1;
				IF(TRIM(LV_TEMPSTR) IS NULL)THEN
					LV_PRIMKEYCOLCOUNT := 0;
				ELSE
					LOOP
						LV_DELIMPOS  := INSTR (LV_TEMPSTR, ',');				
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
							LV_PRIMKEYCOLDATA(LV_INDEX) := LV_TEMPSTR ;
						EXIT;
						ELSE
							LV_PRIMKEYCOLDATA(LV_INDEX) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
							LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
						END IF;
						LV_INDEX := LV_INDEX + 1;
					END LOOP;
					LV_PRIMKEYCOLCOUNT := LV_INDEX;
				END IF;
			--}
			END;
			
			DBMS_OUTPUT.PUT_LINE('LV_INSCOLDATAWITHNUMCOUNT: '||LV_INSCOLDATAWITHNUMCOUNT);
			DBMS_OUTPUT.PUT_LINE('LV_NOOFCOLUMNS: '||LV_NOOFCOLUMNS);
			
			BEGIN
			--{
				IF (LV_INSCOLDATAWITHNUMCOUNT != LV_NOOFCOLUMNS) THEN
				--{
					DBMS_OUTPUT.PUT_LINE('RETURN FROM LINE NUM 314'); 
					RETURN;
				--}
				END IF;
			--}
			END;
			
			------------------------------------------------------
			----ADDITIONAL PARAM VALIDATION
			------------------------------------------------------
			BEGIN
			--{
				IF (LV_ADDNLPARAMCOUNT > 0) THEN
				--{
					FOR LV_INDEX IN 1.. LV_ADDNLPARAMCOUNT LOOP 
					--{
						IF(TRIM(LV_ADDNLPARAMDATA(LV_INDEX)) IS NOT NULL)THEN
						--{
							LV_TEMPSTR := LV_ADDNLPARAMDATA(LV_INDEX);
							LV_DELIMPOS  := INSTR (LV_TEMPSTR, '=');
							IF(LV_DELIMPOS > 0)THEN
								LV_ADDNLPARAMID := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
								LV_ADDNLPARAMVALUE   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
							ELSE
								LV_ADDNLPARAMID := '';
								LV_ADDNLPARAMVALUE := ''; 
							END IF;
						
							--TRIM_COLUMNS
							IF(LV_ADDNLPARAMID = 'TRIM_COLUMNS')THEN
								LV_TEMPSTR := LV_ADDNLPARAMVALUE;
								LV_INDEX1 := 1;
								IF(TRIM(LV_TEMPSTR) IS NULL)THEN
									LV_TRIMCOLCOUNT := 0;
								ELSE
									LOOP
										LV_DELIMPOS  := INSTR (LV_TEMPSTR, ',');				
										IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
											LV_TRIMCOLDATA(LV_INDEX1) := LV_TEMPSTR ;
										EXIT;
										ELSE
											LV_TRIMCOLDATA(LV_INDEX1) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
											LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
										END IF;
										LV_INDEX1 := LV_INDEX1 + 1;
									END LOOP;
									LV_TRIMCOLCOUNT := LV_INDEX1;
								END IF;
							END IF;
						
							--IGNORECOLSIZE_COLUMNS
							IF(LV_ADDNLPARAMID = 'IGNORECOLSIZE_COLUMNS')THEN
								LV_TEMPSTR := LV_ADDNLPARAMVALUE;
								LV_INDEX1 := 1;
								IF(TRIM(LV_TEMPSTR) IS NULL)THEN
									LV_IGNORECOLSIZECOLCOUNT := 0;
								ELSE
									LOOP
										LV_DELIMPOS  := INSTR (LV_TEMPSTR, ',');				
										IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
											LV_IGNORECOLSIZECOLDATA(LV_INDEX1) := LV_TEMPSTR ;
										EXIT;
										ELSE
											LV_IGNORECOLSIZECOLDATA(LV_INDEX1) := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS - 1);
											LV_TEMPSTR   := SUBSTR (LV_TEMPSTR, LV_DELIMPOS + 1);
										END IF;
										LV_INDEX1 := LV_INDEX1 + 1;
									END LOOP;
									LV_IGNORECOLSIZECOLCOUNT := LV_INDEX1;
								END IF;
							END IF;
							
							--UPLD_FILE_COL_COUNT
							IF(LV_ADDNLPARAMID = 'UPLD_FILE_COL_COUNT')THEN
								IF(TRIM(LV_ADDNLPARAMVALUE) IS NOT NULL)THEN
									IF(LV_RECDATACOUNT != TO_NUMBER(LV_ADDNLPARAMVALUE))THEN
										LV_ERR_MSG := LV_ERR_MSG || '|INVALID RECORD. NUMBER OF FIELDS IN THE RECORD IS NOT MATCHING THE FILE FORMAT' ;
									END IF;
								END IF;
							END IF;
						--}
						END IF;
					--}
					END LOOP;
				--}
				END IF;

				EXCEPTION
				WHEN OTHERS THEN
				LV_DB_ERR_CODE := SQLCODE;
				LV_DB_ERR_MSG := SUBSTR(SQLERRM, 1, 200);
				DBMS_OUTPUT.PUT_LINE('EXCEPTION:ADDNLPARAMCOUNT '||LV_DB_ERR_CODE||LV_DB_ERR_MSG);
			--}
			END;
			
			------------------------------------------------------
			----MANDATORY VALIDATION
			------------------------------------------------------
			BEGIN
			--{
				DBMS_OUTPUT.PUT_LINE('MANDATORY VALIDATION : LV_PRIMKEYCOLCOUNT = '||LV_PRIMKEYCOLCOUNT);
				IF (LV_PRIMKEYCOLCOUNT > 0) THEN
				--{
					FOR LV_INDEX IN 1.. LV_PRIMKEYCOLCOUNT LOOP 
					--{
						IF(TRIM(LV_PRIMKEYCOLDATA(LV_INDEX)) IS NOT NULL)THEN
							IF (LV_RECORDCOLDATA(LV_PRIMKEYCOLDATA(LV_INDEX)) IS NULL) THEN
							--{
								DBMS_OUTPUT.PUT_LINE('MANDATORY VALIDATION : LV_PRIMKEYCOLDATA(LV_INDEX) = '||LV_PRIMKEYCOLDATA(LV_INDEX));
								LV_ERR_MSG := LV_ERR_MSG || '|COLUMN ' || LV_PRIMKEYCOLDATA(LV_INDEX) || ' IS MANDATORY' ;
							--}
							END IF ;
						END IF;
					--}
					END LOOP;
				--}
				END IF;

				EXCEPTION
				WHEN OTHERS THEN
				LV_DB_ERR_CODE := SQLCODE;
				LV_DB_ERR_MSG := SUBSTR(SQLERRM, 1, 200);
				DBMS_OUTPUT.PUT_LINE('EXCEPTION:PRIMKEYCOLCOUNT '||LV_DB_ERR_CODE||LV_DB_ERR_MSG);
			--}
			END;
			
			----------------------------------------------------------------
			--DATE VALIDATIONS AND DATE CONVERSIONS(ACCORDING TO UPDATE QUERY)
			----------------------------------------------------------------
			BEGIN
			--{
				IF (LV_DATECOLDATACOUNT > 0) THEN
				--{
					FOR LV_INDEX IN 1.. LV_DATECOLDATACOUNT LOOP
					--{
						LV_DELIMPOS2 := INSTR(LV_DATECOLDATAWITHFORMAT(LV_INDEX),'|');
						LV_SPLITDATECOLUMNS := SUBSTR (LV_DATECOLDATAWITHFORMAT(LV_INDEX), 1, LV_DELIMPOS2 - 1);
						LV_SPLITDATECOLFORMAT := SUBSTR (LV_DATECOLDATAWITHFORMAT(LV_INDEX), LV_DELIMPOS2 + 1);
							
						IF(TO_NUMBER(LV_SPLITDATECOLUMNS) < 10)THEN
							LV_RECNUMFORDATESANDNUMBERS := LV_RECNUMFORDATESANDNUMBERS || 0;
						END IF;	
						LV_RECNUMFORDATESANDNUMBERS := ',' ||LV_RECNUMFORDATESANDNUMBERS ||LV_SPLITDATECOLUMNS|| ',';						
						
						SELECT READ_AND_POPULATE_DATA.COMMON_CHECK_DATE(LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS)),LV_SPLITDATECOLFORMAT) INTO LV_CHECKDATE FROM DUAL;

						IF ((LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS)) = '0') OR  (LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS)) IS NULL)) THEN
						--{
							LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS)) := 'NULL';
						--}
						ELSE
						--{
							IF (LV_CHECKDATE = 1) THEN
							--{
								LV_ERR_MSG := LV_ERR_MSG || '|COLUMN ' || LV_SPLITDATECOLUMNS || ':' || 'INVALID DATE FORMAT';
							--}
							ELSE
							--{
								IF((TRIM(LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS))) IS NOT NULL))THEN
								--{
									LV_DATE := LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS));
									LV_DATE := TO_DATE(LV_DATE,LV_SPLITDATECOLFORMAT);
									LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS)) := '''' || LV_DATE || '''';
								--}
                                ELSE
									LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITDATECOLUMNS)) := '''' || '''';
                                END IF;
							END IF;
						--}
						END IF;
					--}	
					END LOOP;
				--}
				END IF;
				
				EXCEPTION
				WHEN OTHERS THEN
				LV_DB_ERR_CODE := SQLCODE;
				LV_DB_ERR_MSG := SUBSTR(SQLERRM, 1, 200);
				DBMS_OUTPUT.PUT_LINE('EXCEPTION:DATECOLDATACOUNT '||LV_DB_ERR_CODE||LV_DB_ERR_MSG);
			--}
			END;
			
			----------------------------------------------------------------------------
			--NUMBER VALIDATIONS AND NUMBER CONVERSIONS (ACCORDING TO UPDATE QUERY)
			-----------------------------------------------------------------------------
			BEGIN
			--{
				IF (LV_NUMCOLDATACOUNT > 0) THEN
				--{
					DBMS_OUTPUT.PUT_LINE('Inside numder validation');
					FOR LV_INDEX IN 1.. LV_NUMCOLDATACOUNT LOOP
					--{
						IF(TO_NUMBER(LV_NUMCOLDATA(LV_INDEX)) < 10)THEN
							LV_RECNUMFORDATESANDNUMBERS := LV_RECNUMFORDATESANDNUMBERS || 0;
						END IF;							
						IF(TRIM(LV_RECORDCOLDATA(TO_NUMBER(LV_NUMCOLDATA(LV_INDEX)))) IS NOT NULL)THEN
						--{
							DBMS_OUTPUT.PUT_LINE('INSIDE NOT NULL');
						
							LV_RECNUMFORDATESANDNUMBERS := ',' || LV_RECNUMFORDATESANDNUMBERS ||TO_NUMBER(LV_NUMCOLDATA(LV_INDEX))|| ',';
					
							SELECT READ_AND_POPULATE_DATA.COMMON_CHECK_NUMBER(LV_RECORDCOLDATA(TO_NUMBER(LV_NUMCOLDATA(LV_INDEX)))) INTO LV_CHECKNUMBER FROM DUAL;

							IF (LV_CHECKNUMBER = 'F') THEN
							--{
								LV_ERR_MSG := LV_ERR_MSG || '|COLUMN ' || LV_NUMCOLDATA(LV_INDEX) || 'IS NOT A NUMBER';
								LV_RECORDCOLDATA(TO_NUMBER(LV_NUMCOLDATA(LV_INDEX))) := 0 ;
							--}
							END IF;
						--}
                        ELSE
							LV_RECORDCOLDATA(TO_NUMBER(LV_NUMCOLDATA(LV_INDEX))) := NULL;
                        END IF;
					--}	
					END LOOP;
				--}
				END IF;
				
				EXCEPTION
				WHEN OTHERS THEN
				LV_DB_ERR_CODE := SQLCODE;
				LV_DB_ERR_MSG := SUBSTR(SQLERRM, 1, 200);
				DBMS_OUTPUT.PUT_LINE('EXCEPTION:NUMCOLDATACOUNT '||LV_DB_ERR_CODE||LV_DB_ERR_MSG);
			--}
			END;
			
			------------------------------------------------------------------------------
			----LENGTH VALIDATIONS AND STRING CONVERSIONS (ACCORDING TO UPDATE QUERY)
			------------------------------------------------------------------------------
			BEGIN
			--{
				IF (LV_RECDATACOUNT > 0) THEN
				--{
					FOR LV_INDEX IN 1..LV_RECDATACOUNT LOOP
					--{
						IF (LV_INDEX<10) THEN
						--{
							LV_STRING := ',' || '0'|| LV_INDEX || ',';
						--}
						ELSE
						--{
							LV_STRING := ',' || LV_INDEX || ',';
						--}
						END IF;
						
						LV_DELIMPOS  := INSTR (LV_RECNUMFORDATESANDNUMBERS, LV_STRING);
						IF ((LV_DELIMPOS = 0) OR (LV_DELIMPOS IS NULL)) THEN
						--{
							IF (LV_RECORDCOLDATA(LV_INDEX) IS NULL) THEN
							--{
								LV_RECORDCOLDATA(LV_INDEX) := 'NULL';	
							--}
							ELSE
							--{
								IF (LENGTH(LV_RECORDCOLDATA(LV_INDEX)) > TO_NUMBER(LV_COLSIZEDATA(LV_INDEX))) THEN
								--{
									IF (LV_TRIMCOLCOUNT > 0) THEN
									--{
										FOR LV_INDEX1 IN 1..LV_TRIMCOLCOUNT LOOP
										--{
											LV_TEMPSTR := LV_TRIMCOLDATA(LV_INDEX1);
											DBMS_OUTPUT.PUT_LINE('CHECKING TRIM : '||LV_TEMPSTR);
											IF (TO_NUMBER(LV_TEMPSTR) = LV_INDEX) THEN
											--{
												LV_RECORDCOLDATA(LV_INDEX) := '''' || SUBSTR(LV_RECORDCOLDATA(LV_INDEX),0,LV_COLSIZEDATA(LV_INDEX)) || '''';
												EXIT;
											--}
											ELSE
											--{
												LV_ERR_MSG := LV_ERR_MSG || '|COLUMN ' || LV_INDEX || ':' || 'SIZE CANNOT BE MORE THAN' || ':' || LV_COLSIZEDATA(LV_INDEX);
											--}
											END IF;
										--}
										END LOOP;
									--}
									ELSE
										LV_ERR_MSG := LV_ERR_MSG || '|COLUMN ' || LV_INDEX || ':' || 'SIZE CANNOT BE MORE THAN' || ':' || LV_COLSIZEDATA(LV_INDEX);
									END IF;
									
								--}
								ELSE
								--{
									LV_RECORDCOLDATA(LV_INDEX) := '''' || LV_RECORDCOLDATA(LV_INDEX) || '''';
								--}
								END IF;
							--}
							END IF;
						--}
						END IF;
					--}	
					END LOOP;
				--}
				END IF;
			--}
			END;
			
			BEGIN
			--{
				IF (LV_NOOFCOLUMNS > 0) THEN
				--{
					FOR LV_INDEX IN 1..LV_NOOFCOLUMNS LOOP
					--{
						LV_TEMPSTR := LV_INSCOLDATAWITHNUM(LV_INDEX);
						LV_DELIMPOS1 := INSTR(LV_INSCOLDATAWITHNUM(LV_INDEX),'|');
						LV_SPLITCOLUMNS := SUBSTR (LV_TEMPSTR, LV_DELIMPOS1 + 1);
						LV_SPLITCOLUMNNUM := SUBSTR (LV_TEMPSTR, 1, LV_DELIMPOS1 - 1);	
						DBMS_OUTPUT.PUT_LINE('LV_SPLITCOLUMNNUM = '||LV_SPLITCOLUMNNUM);
						IF (LV_INDEX = 1) THEN
						--{
							LV_UPDATECOLUMNS :=  LV_UPDATECOLUMNS || LV_SPLITCOLUMNS || '=' ||  LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITCOLUMNNUM)) || '  ' ;
						--}
						ELSE
						--{
							LV_UPDATECOLUMNS :=  LV_UPDATECOLUMNS|| ',' || LV_SPLITCOLUMNS || '=' || LV_RECORDCOLDATA(TO_NUMBER(LV_SPLITCOLUMNNUM)) || '  ' ;
						--}
						END IF;
					--}
					END LOOP;
				--}
				END IF;
			--}
			END;
			
			----------------------------------------------------------------------------------
			---UPDATING MAIN TABLE ACCORDING TO ERROR MESSAGE
			----------------------------------------------------------------------------------
			DBMS_OUTPUT.PUT_LINE('UPDATING MAIN TABLE');
			DBMS_OUTPUT.PUT_LINE('LV_ERR_MSG:'||LV_ERR_MSG);
			BEGIN
			--{
				LV_TMPRECSRLNUM := TO_NUMBER(LV_RECSRLNUM);
				IF (LV_ERR_MSG IS NULL) THEN
				--{
					DBMS_OUTPUT.PUT_LINE('SUCCESS:'||LV_ERR_MSG);
					LV_UPDATE_QUERY := 'UPDATE' || '  ' || LV_TABLENAME ||  '  ' || 'SET' ||   '  ' || LV_UPDATECOLUMNS || ',' || 'UPLOAD_ERR_MSG=' || '''' || LV_ERR_MSG || '''' || ',' || 'UPLOAD_STATUS=' || '''' || 'S' || '''' || '  WHERE ' || '   ' || 'UPLOAD_BATCH_ID = ' || '''' || LV_UPLOAD_BATCH_ID || '''' || ' AND TO_NUMBER(UPLOAD_REC_SRL_NUM) = ' || LV_TMPRECSRLNUM;
					DBMS_OUTPUT.PUT_LINE(LV_UPDATE_QUERY);
				--}
				ELSE
				--{
					DBMS_OUTPUT.PUT_LINE('FAILURE:'||LV_ERR_MSG);
					LV_ERR_MSG := SUBSTR(LV_ERR_MSG,1,500);
					LV_UPDATE_QUERY := 'UPDATE' || '  ' || LV_TABLENAME ||  '  ' || 'SET ' || '  ' ||  'UPLOAD_ERR_MSG=' || '''' || LV_ERR_MSG || '''' || ',' || 'UPLOAD_STATUS=' || '''' || 'F' || '''' ||  '  WHERE ' || '   ' || 'UPLOAD_BATCH_ID = ' || '''' || LV_UPLOAD_BATCH_ID || '''' || ' AND TO_NUMBER(UPLOAD_REC_SRL_NUM) = ' || LV_TMPRECSRLNUM;
					DBMS_OUTPUT.PUT_LINE(LV_UPDATE_QUERY);
				--}
				END IF;
				BEGIN
					EXECUTE IMMEDIATE LV_UPDATE_QUERY;
				EXCEPTION
				WHEN OTHERS THEN					
					LV_ERR_MSG := SUBSTR(SQLERRM, 1, 500);
					LV_UPDATE_QUERY := 'UPDATE' || '  ' || LV_TABLENAME ||  '  ' || 'SET ' || '  ' ||  'UPLOAD_ERR_MSG=' || '''' || LV_ERR_MSG || '''' || ',' || 'UPLOAD_STATUS=' || '''' || 'F' || '''' ||  '  WHERE ' || '   ' || 'UPLOAD_BATCH_ID = ' || '''' || LV_UPLOAD_BATCH_ID || '''' || ' AND TO_NUMBER(UPLOAD_REC_SRL_NUM) = ' || LV_TMPRECSRLNUM;
					DBMS_OUTPUT.PUT_LINE(LV_UPDATE_QUERY);
					EXECUTE IMMEDIATE LV_UPDATE_QUERY;
				END;
				COMMIT;
			--{
			END;
		END LOOP;
	--}
	END IF;
END READ_AND_POPULATE_DATA_PROC;

